/**
 * iOS-styled alert announcing an upstream release without ever offering to
 * install it. Installing upstream would replace this fork because both share
 * the same package id; the only safe action here is to copy an OpenCode prompt
 * that merges the change into the fork and publishes a fork release instead.
 */
@OptIn(ExperimentalHazeMaterialsApi::class)
@Composable
fun UpstreamUpdateDialog(
    release: UpstreamUpdateChecker.UpstreamRelease,
    hazeState: HazeState,
    onDismiss: () -> Unit,
    onCopyPrompt: () -> Unit,
    onOpenReleasePage: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val reduceDynamicBlur by AppSettings.reduceDynamicBlur.collectAsStateWithLifecycle()
    val shape = RoundedCornerShape(ALERT_CORNER)

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(SCRIM_COLOR)
            .clickable(
                indication = null,
                interactionSource = remember { MutableInteractionSource() },
                onClick = onDismiss,
            ),
        contentAlignment = Alignment.Center,
    ) {
        Column(
            modifier = Modifier
                .width(ALERT_WIDTH)
                .clip(shape)
                .then(
                    if (reduceDynamicBlur) {
                        Modifier.background(MaterialTheme.colorScheme.surface)
                    } else {
                        Modifier.optimizedHazeEffect(
                            state = hazeState,
                            style = HazeMaterials.regular(MaterialTheme.colorScheme.surface),
                        )
                    },
                )
                .clickable(
                    indication = null,
                    interactionSource = remember { MutableInteractionSource() },
                    onClick = {},
                ),
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 19.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
            ) {
                Text(
                    text = "Upstream BitChord update",
                    style = MaterialTheme.typography.bodyLarge.copy(
                        fontSize = 17.sp,
                        fontWeight = FontWeight.W600,
                    ),
                    color = MaterialTheme.colorScheme.onSurface,
                    textAlign = TextAlign.Center,
                )
                Text(
                    text = "Latest upstream release is ${release.tag}. This app will not install it — that would replace your fork. Copy the OpenCode prompt to sync it safely; the fork update will then appear here.",
                    modifier = Modifier.padding(top = 4.dp),
                    style = MaterialTheme.typography.bodyMedium.copy(
                        fontSize = 13.sp,
                        lineHeight = 17.sp,
                    ),
                    color = MaterialTheme.colorScheme.onSurface,
                    textAlign = TextAlign.Center,
                )
            }

            AlertRule()
            AlertAction(
                label = "Copy OpenCode Prompt",
                emphasised = true,
                onClick = onCopyPrompt,
            )
            AlertRule()
            AlertAction(
                label = stringResource(R.string.open_releases_page),
                emphasised = false,
                onClick = onOpenReleasePage,
            )
            AlertRule()
            AlertAction(
                label = stringResource(R.string.later),
                emphasised = false,
                onClick = onDismiss,
            )
        }
    }
}
