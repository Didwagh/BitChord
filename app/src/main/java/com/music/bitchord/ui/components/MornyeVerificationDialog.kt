/**
 * iOS-styled alert for a Mornye extension that needs its session repaired.
 *
 * Never carries the verification URL, callback state, grant or session id.
 * The only safe action is to send the listener to the extension's own Connect
 * screen, or copy plain-text steps.
 */
@OptIn(ExperimentalHazeMaterialsApi::class)
@Composable
fun MornyeVerificationDialog(
    displayName: String,
    hazeState: HazeState,
    onOpenSources: () -> Unit,
    onCopySteps: () -> Unit,
    onDismiss: () -> Unit,
    modifier: Modifier = Modifier,
) {
    val reduceDynamicBlur by AppSettings.reduceDynamicBlur.collectAsStateWithLifecycle()
    val shape = RoundedCornerShape(ALERT_CORNER)

    Box(
        modifier = modifier
            .fillMaxSize()
            .background(SCRIM_COLOR)
            .clickable(
                indication = null,
                interactionSource = remember { MutableInteractionSource() },
                onClick = onDismiss,
            ),
        contentAlignment = Alignment.Center,
    ) {
        Column(
            modifier = Modifier
                .width(ALERT_WIDTH)
                .clip(shape)
                .then(
                    if (reduceDynamicBlur) {
                        Modifier.background(MaterialTheme.colorScheme.surface)
                    } else {
                        Modifier.optimizedHazeEffect(
                            state = hazeState,
                            style = HazeMaterials.regular(MaterialTheme.colorScheme.surface),
                        )
                    },
                )
                .clickable(
                    indication = null,
                    interactionSource = remember { MutableInteractionSource() },
                    onClick = {},
                ),
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 16.dp, vertical = 19.dp),
                horizontalAlignment = Alignment.CenterHorizontally,
            ) {
                Text(
                    text = stringResource(R.string.mornye_verification_title),
                    style = MaterialTheme.typography.bodyLarge.copy(
                        fontSize = 17.sp,
                        fontWeight = FontWeight.W600,
                    ),
                    color = MaterialTheme.colorScheme.onSurface,
                    textAlign = TextAlign.Center,
                )
                Text(
                    text = stringResource(R.string.mornye_verification_body, displayName),
                    modifier = Modifier.padding(top = 4.dp),
                    style = MaterialTheme.typography.bodyMedium.copy(
                        fontSize = 13.sp,
                        lineHeight = 17.sp,
                    ),
                    color = MaterialTheme.colorScheme.onSurface,
                    textAlign = TextAlign.Center,
                )
            }

            AlertRule()
            AlertAction(
                label = stringResource(R.string.mornye_verification_open),
                emphasised = true,
                onClick = onOpenSources,
            )
            AlertRule()
            AlertAction(
                label = stringResource(R.string.mornye_verification_copy_steps),
                emphasised = false,
                onClick = onCopySteps,
            )
            AlertRule()
            AlertAction(
                label = stringResource(R.string.later),
                emphasised = false,
                onClick = onDismiss,
            )
        }
    }
}
